CREATE TABLE identity.email_verification_challenges (
    id uuid NOT NULL,
    user_id bigint NOT NULL,
    purpose character varying(32) NOT NULL,
    email_snapshot character varying(254) NOT NULL,
    normalized_email_snapshot character varying(254) NOT NULL,
    code_mac character varying(64) NOT NULL,
    key_id character varying(32) NOT NULL,
    state integer NOT NULL,
    created_at timestamp with time zone NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    pending_lease_until timestamp with time zone NOT NULL,
    submitted_at timestamp with time zone,
    consumed_at timestamp with time zone,
    invalidated_at timestamp with time zone,
    failed_attempts integer NOT NULL,
    last_attempt_at timestamp with time zone,
    CONSTRAINT "PK_email_verification_challenges" PRIMARY KEY (id),
    CONSTRAINT "CK_EmailVerification_Attempts" CHECK ("failed_attempts" BETWEEN 0 AND 5),
    CONSTRAINT "CK_EmailVerification_Consumed" CHECK (("state" = 4) = ("consumed_at" IS NOT NULL) AND ("consumed_at" IS NULL OR ("consumed_at" >= "created_at" AND "consumed_at" < "expires_at"))),
    CONSTRAINT "CK_EmailVerification_Invalidated" CHECK (("state" IN (3,5,6)) = ("invalidated_at" IS NOT NULL) AND ("invalidated_at" IS NULL OR "invalidated_at" >= "created_at")),
    CONSTRAINT "CK_EmailVerification_KeyId" CHECK ("key_id" ~ '^[A-Za-z0-9_-]{1,32}$'),
    CONSTRAINT "CK_EmailVerification_LastAttempt" CHECK ("last_attempt_at" IS NULL OR "last_attempt_at" >= "created_at"),
    CONSTRAINT "CK_EmailVerification_Locked" CHECK (("state" = 6) = ("failed_attempts" = 5)),
    CONSTRAINT "CK_EmailVerification_Mac" CHECK ("code_mac" ~ '^[0-9A-F]{64}$'),
    CONSTRAINT "CK_EmailVerification_Purpose" CHECK ("purpose" = 'EmailVerification'),
    CONSTRAINT "CK_EmailVerification_State" CHECK ("state" BETWEEN 1 AND 6),
    CONSTRAINT "CK_EmailVerification_Submitted" CHECK (("state" NOT IN (2,4,6) OR "submitted_at" IS NOT NULL) AND ("submitted_at" IS NULL OR ("submitted_at" >= "created_at" AND "submitted_at" < "expires_at"))),
    CONSTRAINT "CK_EmailVerification_Time" CHECK ("expires_at" = "created_at" + interval '5 minutes' AND "pending_lease_until" = "created_at" + interval '2 minutes'),
    CONSTRAINT "FK_email_verification_challenges_users_user_id" FOREIGN KEY (user_id) REFERENCES identity.users (id) ON DELETE CASCADE
);


