CREATE OR REPLACE FUNCTION identity.check_refresh_family() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM identity.user_tokens t JOIN identity.sessions s ON s.user_id=t.user_id WHERE t.id=NEW.id AND s.id=NEW.session_id AND t.token_type='REFRESH')
 OR (NEW.replaced_by_credential_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM identity.refresh_credential_metadata r WHERE r.id=NEW.replaced_by_credential_id AND r.session_id=NEW.session_id))
 THEN RAISE EXCEPTION 'Refresh credential family mismatch' USING ERRCODE='23503'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER check_refresh_family BEFORE INSERT OR UPDATE ON identity.refresh_credential_metadata FOR EACH ROW EXECUTE FUNCTION identity.check_refresh_family();

CREATE TABLE identity_uuid_archive.conversion_manifest(table_name text PRIMARY KEY,fingerprint text NOT NULL);
DO $$ DECLARE t record; value text; BEGIN
FOR t IN SELECT tablename FROM pg_tables WHERE schemaname='identity' AND tablename<>'__EFMigrationsHistory' LOOP
 EXECUTE format($q$SELECT md5(coalesce(string_agg(v,chr(10) ORDER BY v),'')) FROM (SELECT row_to_json(r)::text v FROM identity.%I r) q$q$,t.tablename) INTO value;
 INSERT INTO identity_uuid_archive.conversion_manifest VALUES(t.tablename,value);
END LOOP; END $$;
