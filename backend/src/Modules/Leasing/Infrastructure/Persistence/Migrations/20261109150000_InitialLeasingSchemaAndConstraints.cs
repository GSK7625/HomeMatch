CREATE OR REPLACE FUNCTION public.fn_trg_sync_contract_room_status()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.status IN ('ACTIVE', 'EXPIRED_PENDING_HANDOVER', 'HANDOVER_OVERDUE')
       OR (NEW.status = 'TERMINATED' AND NEW.handover_confirmed_at IS NULL) THEN
        -- Mark room RENTED and hide published listing
        UPDATE properties.rooms
        SET status = 'RENTED', updated_at = now()
        WHERE id = NEW.room_id AND status <> 'RENTED';

        UPDATE listings.listings
        SET status = 'HIDDEN', updated_at = now()
        WHERE room_id = NEW.room_id AND status = 'PUBLISHED';

    ELSIF NEW.status IN ('COMPLETED', 'REJECTED', 'SIGNATURE_EXPIRED', 'CANCELLED')
       OR (NEW.status = 'TERMINATED' AND NEW.handover_confirmed_at IS NOT NULL) THEN
        -- Only release room to AVAILABLE if room is currently RENTED and no other reserving contract occupies it
        UPDATE properties.rooms r
        SET status = 'AVAILABLE', updated_at = now()
        WHERE r.id = NEW.room_id
          AND r.status = 'RENTED'
          AND NOT EXISTS (
              SELECT 1 FROM leasing.contracts c
              WHERE c.room_id = r.id 
                AND c.id <> NEW.id
                AND (c.status IN ('PENDING_SIGNATURE', 'SIGNED', 'ACTIVE', 'EXPIRED_PENDING_HANDOVER', 'HANDOVER_OVERDUE')
                     OR (c.status = 'TERMINATED' AND c.handover_confirmed_at IS NULL))
          );
    END IF;
    RETURN NEW;
END;
$$;

